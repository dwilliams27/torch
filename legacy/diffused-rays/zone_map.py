def get_zone_style(x: float, y: float) -> int:
    """Get the style index for a given position.

    Args:
        x: Player x position (float)
        y: Player y position (float)

    Returns:
        Style index (0-7)
    """
    # Convert to grid coordinates
    grid_x = int(x)
    grid_y = int(y)

    # Clamp to valid range
    grid_x = max(0, min(grid_x, len(ZONE_MAP[0]) - 1))
    grid_y = max(0, min(grid_y, len(ZONE_MAP) - 1))

    return ZONE_MAP[grid_y][grid_x]
